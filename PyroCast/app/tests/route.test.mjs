import assert from 'node:assert/strict';
import fs from 'node:fs';
import {readRouteGraph,findRoute,contains} from '../web/route/graph.js';
import {createStore} from '../web/state/store.js';
const path=process.argv[2];
if(!path)throw Error('Pass the existing building.json path');
const building=JSON.parse(fs.readFileSync(path,'utf8')),before=JSON.stringify(building);
const g=readRouteGraph(building),r=findRoute(g,'CAD_3F_R2');
assert.equal(g.edges.length,g.sourceEdgeCount);
assert.deepEqual(g.edges.map(e=>e.source),[...building.floors.flatMap(f=>f.simulation_graph?.connections||[]),...building.vertical_connections]);
assert.ok(g.edges.filter(e=>e.source.kind==='open_passage').every(e=>e.eligible));
assert.ok(g.edges.filter(e=>e.source.kind==='door_elev'||e.source.kind==='elev').every(e=>!e.eligible));
assert.equal(g.mainEntrance.id,'CAD_1F_D3');
assert.equal(contains(g.defaultVehicle,g.ground.slab),false);
assert.ok(Math.abs(Math.hypot(...g.defaultVehicle.map((x,i)=>x-g.mainEntrance.point[i]))-5)<1e-9);
assert.equal(r.stairs,2);assert.equal(r.hoses,Math.ceil(r.length/15));
assert.ok(r.edges.every(e=>g.edges.find(x=>x.id===e.id).eligible));
assert.ok(r.edges.filter(e=>e.kind==='stair').every(e=>e.stair_length===e.rise*1.5));
const plain=findRoute(g,'CAD_3F_R2',undefined,{stair_factor:1});
assert.ok(Math.abs(r.length-plain.length-5.5)<1e-8);
const hose=findRoute(g,'CAD_3F_R2',undefined,{hose_m:20});
assert.equal(hose.length,r.length);assert.equal(hose.hoses,5);
assert.equal(findRoute(g,'absent').error,'선택 실의 연결 정보 없음');
const moved=findRoute(g,'CAD_3F_R2',[60,20,g.ground.z]);
assert.notEqual(moved.entry,r.entry);assert.notEqual(moved.length,r.length);
assert.equal(JSON.stringify(building),before,'route does not mutate input/simulation');
const closed=structuredClone(building);for(const f of closed.floors)for(const c of f.simulation_graph.connections){c.open=false;c.open_fraction=0;}
assert.deepEqual(findRoute(readRouteGraph(closed),'CAD_3F_R2').edges,r.edges,'door fire ventilation state does not block firefighter route');
const store=createStore(),physics=['building','result','screening','realView','risk'].map(k=>store.get(k));
store.dispatch('route/set',{vehicle:[60,20,5.1],hose_m:20,stair_factor:2});
for(const [i,k] of ['building','result','screening','realView','risk'].entries())assert.equal(store.get(k),physics[i]);
assert.throws(()=>store.dispatch('route/set',{vehicle:[NaN,0,0]}));
assert.throws(()=>store.dispatch('route/set',{stair_factor:0}));
console.log(JSON.stringify({passed:true,source_edges:g.sourceEdgeCount,retained_edges:g.edges.length,eligible:r.traversable_edges,length:r.length,hoses:r.hoses,stairs:r.stairs,entry:r.entry,moved:{entry:moved.entry,length:moved.length}},null,2));
