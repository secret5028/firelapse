const c={room:'R3',state:'fixed',result_folder:'test',times:{total_s:1},burning_room_count:2,first_FO_s:40,safe_end_s:3600,complete:true};
const saved={records:[{identity:[c.room,c.state,c.result_folder,1,2,40,3600],complete:true,unknown_rooms:[],attention_room_count:3}]};
const comparison={opening_mode:'fixed',rows:[{room:'R3',state_results:[c]}]};
