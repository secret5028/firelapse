import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import {pathToFileURL} from 'node:url';
import {RouteLayer} from '../web/layers/route.js';
import {CoreLayer} from '../web/layers/core.js';
import {readLegacyCoreSource} from '../web/adapters/legacy_core.js';
import {readRouteGraph} from '../web/route/graph.js';
import {createStore} from '../web/state/store.js';
const T=await import(pathToFileURL(process.argv[2]).href);
globalThis.document={createElement:()=>({getContext:()=>({beginPath(){},arc(){},fill(){},stroke(){},fillText(){}})})};
const raw=fs.readFileSync('data/parkmarine-hotel/building.json'),b=JSON.parse(raw),hash=crypto.createHash('sha256').update(raw).digest('hex');
const graph=readRouteGraph(b),store=createStore(),scene=new T.Scene(),vehicle=new T.Group();
vehicle.add(new T.Mesh(new T.BoxGeometry(),new T.MeshBasicMaterial()));
let target='CAD_7F_R16';
const route=new RouteLayer(T,{graph,vehicleSource:vehicle,targetFor:()=>target});route.mount(scene,store);
const groups=b.floors.map(f=>{const g=new T.Group();g.name=f.name;g.position.z=f.z;g.visible=f.name==='7F';return g;});
const asset=readLegacyCoreSource({building:b,groups,sourceHash:hash,shapeFor:p=>{const s=new T.Shape(p.o.map(v=>new T.Vector2(...v)));for(const h of p.h||[])s.holes.push(new T.Path(h.map(v=>new T.Vector2(...v))));return s;}});
const core=new CoreLayer(T,{geometryFor:()=>asset,contextFloorsFor:()=>route.result?.segments?.map(s=>s.floor)||[]});core.mount(scene,store);
const frame={building:{source_hash:hash},route:store.get('route'),floor:{floor_id:'7F'},layers:{route:true}};
route.setData(frame);core.setData(frame);core.tick();
assert(!route.result.error);assert.equal(route.result.stairs,6);
assert(route.items.every(x=>x.object.visible));assert([...route.roomMaterials.values()].every(m=>m.color.getHexString()==='ffffff'),'hose stays white');assert.equal(route.getVehiclePickPlanes().length,1);
const visible=core.views.filter(v=>v.group.visible).map(v=>v.row.id);
assert.deepEqual(visible,['1F','2F','3F','4F','5F','6F','7F']);
assert(groups.filter(g=>g.visible).every(g=>g.name==='7F'),'lower architectural floors stay hidden');
for(const v of core.views)for(const o of v.group.children)assert.equal(o.material.opacity,o.material.userData.coreOpacity*(v.row.group.position.z<groups.find(g=>g.name==='7F').position.z?.35:1));
target='CAD_9F_R15';route.setData(frame);core.tick();assert(core.views.filter(v=>['8F','9F','10F','PH'].includes(v.row.id)).every(v=>!v.group.visible),'above selected floor hidden even when route target is higher');
core.setData({...frame,layers:{route:false}});core.tick();assert.deepEqual(core.views.filter(v=>v.group.visible).map(v=>v.row.id),['7F']);
core.setData(frame);core.setVisible(false);core.tick();assert.equal(core.group.visible,true);assert.deepEqual(core.views.filter(v=>v.group.visible).map(v=>v.row.id),['7F']);
core.setVisible(true);core.tick();assert.deepEqual(core.views.filter(v=>v.group.visible).map(v=>v.row.id),visible);
route.setData({...frame,route:{...frame.route,vehicle_visible:false}});assert.equal(route.getVehiclePickPlanes().length,0);
assert(route.items.filter(x=>x.route).every(x=>x.object.visible));
target='CAD_7F_R6';route.setData(frame);assert.equal(route.result.target,target);assert(!route.result.error);
route.setVisible(false);assert.equal(route.group.visible,false);
console.log(JSON.stringify({pass:true,selectedFloor:'7F',visibleCoreFloors:visible,stairs:6,allRouteItemsVisible:true,lowerArchitectureHidden:true,toggles:true,roomSwitch:true}));
core.dispose();route.dispose();assert.equal(scene.children.length,0);
