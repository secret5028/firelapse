assert.equal(attentionRanking(comparison,saved)[0].rank2,1);
assert.equal(attentionRanking({...comparison,opening_mode:'extremes'},saved)[0].rank2,null);
assert.equal(attentionRanking(comparison,{records:[]})[0].rank2,null);
