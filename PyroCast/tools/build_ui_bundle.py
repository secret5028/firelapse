"""Bundle the closed frontend module graph into the existing /cfbt/overlay.js URL.

No server-route or engine/cache changes. Only named imports and exported named
declarations are supported: unsupported syntax fails rather than silently rewriting.
Frozen legacy renderers remain external imports, never copied/transformed.
"""
from pathlib import Path
import re
import argparse

ROOT=Path(__file__).resolve().parents[1]
IMPORT=re.compile(r"^import\s+\{([^}]+)\}\s+from\s+['\"]([^'\"]+)['\"];",re.M)
EXPORT=re.compile(r'\bexport\s+(?:async\s+)?(?:function|class|const|let)\s+(\w+)')

def build(output):
    # Generated value-transfer module: display constants have one editable source.
    import json
    config=json.loads((ROOT/'config/display.json').read_text('utf-8'))
    if not (0 <= config['soot_default'] <= 1 and config['glow_full_C'] > config['glow_start_C']):
        raise ValueError('Invalid display configuration')
    renderer=ROOT/'simulation/viewer/legacy_real_view.js'
    text=renderer.read_text('utf-8')
    block='// BEGIN generated display config\nexport const displayConfig = '+json.dumps(config,ensure_ascii=False,indent=2)+';\n// END generated display config'
    text,count=re.subn(r'// BEGIN generated display config[\s\S]*?// END generated display config',lambda m:block,text)
    if count!=1:raise ValueError('Missing display config marker')
    renderer.write_text(text,encoding='utf-8',newline='\n')
    modules={};ordered=[];externals={};visiting=set()
    def visit(file):
        file=file.resolve()
        if file in modules:return modules[file]
        if file in visiting:raise ValueError('Circular import: '+str(file))
        visiting.add(file);text=file.read_text('utf-8');exports=EXPORT.findall(text)
        def replace(m):
            names,url=m.groups()
            names=re.sub(r'\s+as\s+',':',names)
            if url.startswith('/cfbt/') or 'simulation/viewer/' in url:
                url='/cfbt/'+url.rsplit('/',1)[1]
                if url not in externals:externals[url]='__external'+str(len(externals))
                dep=externals[url]
            else:dep=visit(file.parent/url)
            return 'const {'+names+'}='+dep+';'
        text=IMPORT.sub(replace,text)
        if re.search(r'^import\s',text,re.M):raise ValueError('Unsupported import in '+str(file))
        text=re.sub(r'\bexport\s+(?=(?:async\s+)?(?:function|class|const|let)\b)','',text)
        if re.search(r'^export\s',text,re.M):raise ValueError('Unsupported export in '+str(file))
        name='__module'+str(len(modules));modules[file]=name
        ordered.append('// '+file.relative_to(ROOT).as_posix()+'\nconst '+name+'=(()=>{\n'+text+'\nreturn {'+','.join(exports)+'};\n})();\n')
        visiting.remove(file);return name
    entry=visit(ROOT/'app/web/entry.js')
    header='// Generated by tools/build_ui_bundle.py. Edit app/web sources; legacy shaders are external.\n'
    header+=''.join('import * as '+var+' from '+repr(url)+';\n' for url,var in externals.items())
    output.parent.mkdir(parents=True,exist_ok=True)
    output.write_text(header+'\n'.join(ordered)+'\nexport const attach='+entry+'.attach;\n',encoding='utf-8',newline='\n')
    print(f'{len(modules)} modules -> {output}, {output.stat().st_size} bytes')

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--output',type=Path,default=ROOT/'simulation/viewer/overlay.js');args=parser.parse_args();build(args.output)
