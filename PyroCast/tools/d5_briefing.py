"""Fill the approved briefing from recorded tools; missing evidence stays missing."""
import re
from d5_tools import finite
from d5_match import match_timelines

LIMITS='지수 100 = 조건 충족, 발생 확정 아님 · 개구부 고정 가정 · 간략 엔진 후반 온도 저평가 · 현장 지휘관 판단 우선'
SIGNS='상층 화염·중립면 급강하·개구부 유속 증가 = FO 전조 / 맥동·뜨거운 문·기름 응축 = BD 전조'


def fill(service,args):
    from lite_ai_briefing import stamp,number
    from lite_ai_tools import display_label,display_text
    calls=[]
    def get(name,**kw):
        r=service.call(name,{**args,**kw});calls.append(r);return r['data']
    summary=get('get_case_summary');origin=summary['origin']
    route=get('get_route',origin=service.case(args).get('route_target_room_id') or origin)
    route_ids=list(dict.fromkeys(r['id'] for seg in route['hose_segments'] for r in seg['rooms'] if r['id']))
    wins={}
    for rid in [*route_ids,origin]:
        wins[rid]={k:get('get_index_windows',room=rid,phenomenon=k) for k in ('FO','FGI','BD','rollover')}
    rules=get('get_tactic_rules')
    building=get('get_building')
    names={r['id']:display_label(r['id'],r.get('name')) for r in building['rooms']}
    def label(rid):return names.get(rid,display_label(rid))
    timelines={}
    for rid in dict.fromkeys([*route_ids,origin]):
        if service.cells(service.case(args),rid):timelines[rid]=get('get_room_timeline',room=rid)
        else:timelines[rid]={'cells':[]}
    log=match_timelines(timelines,building,route,rules,origin)
    now=args.get('time_s',0);used=set();rendered=[]
    # Every paragraph is generated by this function, never a model-authored claim.
    def action(m):
        used.add(m['code']);rendered.append(m)
        return '['+m['code']+'] '+m['text']+' · '+m['notice']
    def window(w):return stamp(w['t_start'])+'~'+(stamp(w['t_end']) if w['t_end'] is not None else '저장 끝')
    def active(m):return m['t_start']<=now and (m['t_end'] is None or now<m['t_end'])
    def event_text(e):return f"{label(e['room'])} ({'BD' if e['phenomenon']=='backdraft' else e['phenomenon']} {number(e['peak'])} @{stamp(e['peak_s'])})"
    use=next((r for r in building['rooms'] if r['id']==origin),{})
    states=building['supply_counts']
    first=[]
    for kind,key in [('FGI','FGI'),('BD','backdraft'),('FO','FO')]:
        event=summary['first_100'].get(key)
        known=any(finite(e.get('peak')) for e in summary['events'][key])
        first.append(kind+' 100 '+(stamp(event['first_s']) if event else '조건 미달' if known else '미평가'))
    worst=max((e for e in summary['worst'].values() if e is not None and finite(e.get('peak'))),key=lambda e:e['peak'],default=None)
    risks=sorted((e for es in summary['events'].values() for e in es if e['room'] in route_ids and finite(e['peak']) and e['peak']>=70),key=lambda e:-e['peak'])
    smoke=min(((r['time_s'],rid,c['cell']) for rid in route_ids for c in timelines[rid]['cells'] for r in c['rows'] if finite(r['h']) and r['h']<=1.8),default=None)
    head=f"[{label(origin)} · 사례 {args['case']} · {summary['engine']} · 브리핑]"
    lines=[head,
        f"화점: {label(origin)} ({use.get('usage') or '용도 미평가'}, 연료 {number(use.get('load'))} MJ/m²) · 급기: 닫힘 {states['closed']}/열림 {states['open']}/미확인 {states['unknown']} · {building['supply_basis']}",
        '진행: '+' → '.join(first),
        '최악: '+(event_text(worst) if worst else '미평가'),
        '경로 위험 실: '+(' · '.join(event_text(e) for e in risks) or '해당 없음 · 미평가는 안전 판정 아님'),
        '연기: 경로상 연기층 ≤1.8 m 최초 '+(label(smoke[1])+' @'+stamp(smoke[0]) if smoke else '확인되지 않음'),
        '교재 전조 대응표: '+SIGNS]
    sections=[dict(title='■ 1. 화재 위험 요약',text='\n'.join(lines))]
    r=route['route'];parts=[]
    if r.get('error'):parts.append('진입 경로 미평가: '+display_text(r['error']))
    else:
        vehicle=', '.join(number(v) for v in r.get('vehicle',[])) or '미평가'
        parts.append(f"진입 경로: 총 {r['hoses']}본 · {number(r['length'])} m · 계단 {r['stairs']}회 · 차량 좌표 ({vehicle}) m")
    for seg in route['hose_segments']:
        ids=list(dict.fromkeys(room['id'] for room in seg['rooms'] if room['id']))
        text=[f"{seg['n']}본 ({number(seg['from_m'])}–{number(seg['to_m'])} m) "+' → '.join(label(room['id']) if room['id'] else '외부' for room in seg['rooms'])]
        for rid in ids:
            for cell in timelines[rid]['cells']:
                current=next((row for row in reversed(cell['rows']) if row['time_s']<=now),None)
                peak=max((e for es in summary['events'].values() for e in es if e['room']==rid and finite(e['peak'])),key=lambda e:e['peak'],default=None)
                text.append(f"상태: {label(rid)} · 셀 {display_text(cell['cell'])} · "+
                    (f"{stamp(current['time_s'])} 상층 {number(current['Tu'])} ℃ · 연기층 {number(current['h'])} m · 전 시간 최고 "+(event_text(peak) if peak else '미평가') if current else '미평가'))
            if not timelines[rid]['cells']:text.append('상태: '+label(rid)+' · 미평가')
        current=[m for m in log if m['room'] in ids and active(m)]
        seen=set()
        for m in current:
            key=(m['room'],m['code'],m['door_id'])
            if key in seen:continue
            seen.add(key)
            text.append('할 일: '+label(m['room'])+(' · '+display_text(m['door_id']) if m['door_id'] else '')+' '+action(m))
        if not current:text.append('할 일: 판정자료 미평가' if ids else '할 일: 실 상태 미평가 (외부 구간)')
        parts.append('\n'.join(text))
    # Fire-door actions are time windows; they do not masquerade as current conditions.
    doorlines=['화점실 문 앞: '+label(origin)]
    doors=[o for o in building['openings'] if origin in o.get('sides',[]) and 'door' in (o.get('kind') or '')]
    doorlines.append('문 상태: '+(' · '.join(display_text(o['id'])+' '+{'open':'열림','closed':'닫힘','unknown':'미확인'}[o['state']] for o in doors) or '미확인'))
    for kind in ('BD','FGI','FO'):
        data=wins[origin][kind]
        doorlines.append('시간창 '+kind+' ≥100: '+(' · '.join(window(w) for w in data['windows']) or ('조건 미달' if data['evaluated'] else '미평가')))
    for m in log:
        if m['room']==origin and m['code'] not in ('C-1','V-1','V-2'):
            doorlines.append('할 일: '+window(m)+(' · '+display_text(m['door_id']) if m['door_id'] else '')+' '+action(m))
    parts.append('\n'.join(doorlines))
    sections.append(dict(title='■ 2. 수관 구간별 할 일',text='\n\n'.join(parts)))
    common=next(x for x in rules['rules'] if x['code']=='G-0')
    sections.append(dict(title='■ 3. 공통',text=action({**common,'notice':rules['notice']})))
    refs=list(dict.fromkeys(x['ref']['doc'] for x in rendered))
    sections.append(dict(title='■ 4. 한계',text=LIMITS+'\n근거: 도구 호출 '+str(len(calls))+'회 · 규칙 '+' '.join(sorted(used))+' · 교재 '+'; '.join(refs)))
    text='\n\n'.join(x['title']+'\n'+x['text'] for x in sections)
    return dict(building=args['building'],case=args['case'],text=text,sections=sections,facts=[],calls=calls,
                rules=sorted(used),proposals=[],status='',matching_log=log,rendered_rules=rendered,
                template_version='D5/1',polishing='offline deterministic',time_s=now)
