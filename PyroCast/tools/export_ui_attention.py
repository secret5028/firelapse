"""Read saved screening series; export UI-only >=70 room counts. No simulation."""
import hashlib
import json
import logging
import math
from pathlib import Path
from result_catalog import atomic_json, read

ROOT = Path(__file__).resolve().parents[1]
KINDS = ('FO', 'FGI', 'backdraft')


def summarize(result):
    hit, unknown = set(), set()
    for row in result['room_summary']:
        room = row['original_room']
        for kind in KINDS:
            values = result['shared_conditions']['rooms'][row['cell']].get(kind, {}).get('scores', {}).get('degree')
            if not isinstance(values, list) or len(values) != len(result['t']):
                unknown.add(room)
                continue
            for value in values:
                if not isinstance(value, (int, float)) or not math.isfinite(value):
                    unknown.add(room)
                elif value * 100 >= 70:
                    hit.add(room)
    # Unknown values cannot undo an already known >=70 hit in the same room.
    return dict(attention_rooms=sorted(hit), attention_room_count=len(hit), unknown_rooms=sorted(unknown - hit))


def result_index(source):
    """Persist an index beside each result, invalidated by the source file stamp."""
    source=Path(source).resolve()
    if not source.exists():
        # Results-only distributions retain the original small index, sealed to
        # the exact saved playback. New calculations still use raw result.json.
        portable=read(source.with_name('portable-result-index.json'),{})
        value=portable.get('index',{})
        playback=source.with_name('playback.json')
        sealed=hashlib.sha256(json.dumps(value,sort_keys=True,separators=(',',':')).encode()).hexdigest()
        if (portable.get('schema')=='firelapse.portable-result-index/1'
                and value.get('schema')=='pyrocast.result-index/1'
                and value.get('threshold')==70 and value.get('kinds')==list(KINDS)
                and portable.get('index_sha256')==sealed and playback.is_file()
                and portable.get('playback_sha256')==hashlib.sha256(playback.read_bytes()).hexdigest()):
            return value
        raise ValueError('저장 결과 요약의 무결성을 확인할 수 없습니다')
    stat=source.stat();stamp=[stat.st_mtime_ns,stat.st_size]
    target=source.with_name('index-summary.json');cached=read(target,{})
    if cached.get('schema')=='pyrocast.result-index/1' and cached.get('source_stamp')==stamp and cached.get('kinds')==list(KINDS):return cached
    raw=source.read_bytes();result=json.loads(raw)
    value={'schema':'pyrocast.result-index/1','threshold':70,'kinds':list(KINDS),
        **summarize(result),'complete':bool(result['ok']),
        'source_stamp':stamp,'source_sha256':hashlib.sha256(raw).hexdigest()}
    atomic_json(target,value);return value


def comparison_attention(comparison, root=None):
    root=Path(root or ROOT/'simulation/results').resolve();records=[];attention_skipped=0
    for pair in (comparison or {}).get('rows',[]):
        for case in pair.get('state_results',[]):
            if not case.get('selected_attempt'):continue
            from runtime_storage import is_result_path
            try:
                source=(Path(case['result_folder'])/case['selected_attempt']/'result.json').resolve()
                if not source.is_relative_to(root) and not (root==(ROOT/'simulation/results').resolve() and is_result_path(source)):raise ValueError('Result outside workspace')
            except ValueError:
                attention_skipped+=1
                logging.warning('screening attention skipped: result outside workspace: %s', 'result.json')
                continue
            try:record=dict(result_index(source))
            except (OSError,ValueError,KeyError,TypeError):continue
            record.update(identity=[case['room'],case['state'],case['result_folder'],case['times']['total_s'],case['burning_room_count'],case['first_FO_s'],case['safe_end_s']],complete=bool(case['complete'] and record['complete']))
            records.append(record)
    return dict(schema='pyrocast.ui-attention/1',threshold=70,kinds=list(KINDS),records=records,attention_skipped=attention_skipped,
                basis='union of original rooms across cells/time; any phenomenon degree*100 >=70; no simulation')


def main():
    cfg = json.loads((ROOT / 'simulation/config/lite-screening-selection.json').read_text('utf-8'))
    comparison = json.loads((Path(cfg['result_path']) / 'comparison.json').read_text('utf-8'))
    payload=comparison_attention(comparison);records=payload['records']
    dest = ROOT / 'app/web/data/saved_attention.js'
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text('// Generated by tools/export_ui_attention.py from saved results only.\nexport const savedAttention = ' + json.dumps(payload, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8', newline='\n')
    print(json.dumps([dict(room=r['identity'][0], state=r['identity'][1], count=r['attention_room_count'], unknown=len(r['unknown_rooms'])) for r in records]))


if __name__ == '__main__':
    main()
