"""Read-only upstream verification and explicit source ownership for builds."""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
TAG = 'CFAST-7.7.7'
SOURCE_LOCK_SHA256 = '5133c2ec046c83472c942aab2d40731f95d84c9358867a4878344190fa4153c7'
VENDOR = ROOT/'vendor/cfast-7.7.7'
ORDER = '''prec cfast_parameters cfast_structures cfast_data convection keyboard_gnu
srev cfastexit utilities ssHeaders outputdebug compartments conduction flowfan
flowhorizontal flowvertical fire numerics radiation target outputsmv
outputspreadsheet output solve initialization input_namelist input cfast'''.split()


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def source_lock(vendor=VENDOR):
    """The checked-in lock is authoritative, never regenerated by fetching."""
    vendor=Path(vendor)
    if digest(vendor/'sources.json')!=SOURCE_LOCK_SHA256:
        raise ValueError('Pinned CFAST source lock was modified; update the release pin explicitly')
    lock=json.loads((vendor/'sources.json').read_text(encoding='utf-8'))
    expected={name+'.f90' for name in ORDER}
    records=lock['files']
    if lock['tag']!=TAG or len(records)!=len(expected) or {r['file'] for r in records}!=expected:
        raise ValueError('CFAST source lock does not match the pinned build inventory')
    for record in records:
        url=f"https://raw.githubusercontent.com/firemodels/cfast/{TAG}/Source/CFAST/{record['file']}"
        sha=record['sha256']
        if record['url']!=url or len(sha)!=64 or any(c not in '0123456789abcdef' for c in sha):
            raise ValueError('Invalid pinned upstream provenance: '+record['file'])
    return lock


def verify_upstream(vendor=VENDOR):
    vendor=Path(vendor);lock=source_lock(vendor)
    records={r['file']:r for r in lock['files']}
    actual={p.name for p in (vendor/'Source').glob('*.f90')}
    if actual!=set(records):
        raise ValueError('Upstream source inventory changed; do not add project code to vendor/')
    for name,record in records.items():
        if digest(vendor/'Source'/name)!=record['sha256']:
            raise ValueError('Upstream CFAST was modified: '+name)
    return {'tag':TAG,'source_lock_sha256':digest(vendor/'sources.json'),
            'verified_files':len(records),'files':records}
