import assert from 'node:assert/strict';
import {createStore} from '../web/state/store.js';
import {attentionRanking} from '../web/adapters/attention.js';
const store=createStore();
assert.equal(store.get('realView').temperaturePattern,'weak');
assert.equal(store.get('realView').smokeColor,'current');
assert.equal(store.get('realView').flameDisplay,'hrr');
